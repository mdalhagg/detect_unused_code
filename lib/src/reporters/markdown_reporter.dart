import 'dart:io';

import '../assets/asset_models.dart';
import '../models.dart';
import '../packages/package_dep_models.dart';
import '../version.dart';

/// Formats and generates GitHub Flavored Markdown (GFM) reports for CI/CD environments.
class MarkdownReporter {
  /// The code analysis report.
  final AnalysisReport report;

  /// Optional external dependencies report.
  final PackageDependenciesReport? depReport;

  /// Optional assets and fonts report.
  final AssetAnalysisReport? assetReport;

  /// Root directory of the project.
  final Directory projectRoot;

  /// Creates a new [MarkdownReporter].
  MarkdownReporter({
    required this.report,
    required this.projectRoot,
    this.depReport,
    this.assetReport,
  });

  /// Generates the full Markdown report as a string.
  String generate() {
    final buffer = StringBuffer();

    final totalDeadClasses = report.deadClasses.length;
    final totalCommentedFiles = report.fullyCommentedFiles.length;
    final totalDeadBlocks = report.filesWithCommentBlocks.length;
    final totalUnusedImports = report.unusedImports.length;
    final totalDiagnostics = report.diagnostics.length;
    final totalTodos = report.todos.length;
    final totalUnusedDeps = depReport?.issues.length ?? 0;
    final totalUnusedAssets = assetReport?.unusedAssets.length ?? 0;
    final reclaimableAssetBytes = assetReport?.totalReclaimableBytes ?? 0;

    final hasCriticalIssues = totalDeadClasses > 0 ||
        totalCommentedFiles > 0 ||
        totalDeadBlocks > 0 ||
        totalUnusedDeps > 0 ||
        totalUnusedAssets > 0 ||
        totalUnusedImports > 0;

    // 1. Header & Title
    buffer.writeln('# 🔎 Detect Unused Code Audit Report');
    buffer.writeln();
    buffer.writeln(
        '> **Generated by [detect_unused_code](https://github.com/mdalhagg/detect_unused_code) v$packageVersion** | ⚡ Powered by [@mdalhagg](https://github.com/mdalhagg)');
    buffer.writeln();

    // 2. Status Badge & Summary
    if (hasCriticalIssues) {
      buffer.writeln('### ⚠️ Status: Action Recommended (Issues Detected)');
    } else {
      buffer
          .writeln('### ✅ Status: Workspace Clean (No Critical Issues Found)');
    }
    buffer.writeln();

    // 3. Executive Metrics Table
    buffer.writeln('## 📊 Executive Summary');
    buffer.writeln();
    buffer.writeln('| Category | Count | Status |');
    buffer.writeln('| :--- | :---: | :---: |');
    buffer.writeln(
        '| **Scanned Dart Files** | `${report.totalTargetDartFiles}` | ℹ️ |');
    buffer.writeln(
        '| **Dead Classes & Widgets** | `$totalDeadClasses` | ${totalDeadClasses == 0 ? "✅ Clean" : "❌ Dead Code"} |');
    buffer.writeln(
        '| **100% Commented Files** | `$totalCommentedFiles` | ${totalCommentedFiles == 0 ? "✅ Clean" : "⚠️ Abandoned"} |');
    buffer.writeln(
        '| **Files with Dead Code Blocks** | `$totalDeadBlocks` | ${totalDeadBlocks == 0 ? "✅ Clean" : "⚠️ Abandoned"} |');
    buffer.writeln(
        '| **Unused / Duplicate Packages** | `$totalUnusedDeps` | ${totalUnusedDeps == 0 ? "✅ Clean" : "📦 Bloat"} |');
    buffer.writeln(
        '| **Unused Media Assets & Fonts** | `$totalUnusedAssets` (${formatByteSize(reclaimableAssetBytes)}) | ${totalUnusedAssets == 0 ? "✅ Clean" : "🖼️ Bloat"} |');
    buffer.writeln(
        '| **Unused & Redundant Imports** | `$totalUnusedImports` | ${totalUnusedImports == 0 ? "✅ Clean" : "🧹 Clutter"} |');
    buffer.writeln(
        '| **Analyzer Diagnostics** | `$totalDiagnostics` | ${totalDiagnostics == 0 ? "✅ Clean" : "🔍 Diagnostics"} |');
    buffer.writeln('| **Pending TODO Tasks** | `$totalTodos` | 📝 Info |');
    buffer.writeln();

    // 4. Dead Classes Section
    if (totalDeadClasses > 0) {
      buffer.writeln('## 💀 Dead Classes & Widgets ($totalDeadClasses)');
      buffer.writeln();
      buffer.writeln(
          '<details><summary><b>Click to expand detected dead classes</b></summary>');
      buffer.writeln();
      buffer.writeln('| Class Name | Category | File Location | Line |');
      buffer.writeln('| :--- | :--- | :--- | :---: |');
      for (final c in report.deadClasses) {
        buffer.writeln(
            '| `${c.name}` | `${c.category}` | `${c.relPath}` | `${c.line}` |');
      }
      buffer.writeln();
      buffer.writeln('</details>');
      buffer.writeln();
    }

    // 5. Unused External Packages
    if (depReport != null && depReport!.issues.isNotEmpty) {
      buffer.writeln(
          '## 📦 Unused & Duplicate External Packages ($totalUnusedDeps)');
      buffer.writeln();
      buffer.writeln(
          '<details><summary><b>Click to expand unused package dependencies</b></summary>');
      buffer.writeln();
      buffer.writeln(
          '| Package Name | Scope | Issue Type | pubspec.yaml Location |');
      buffer.writeln('| :--- | :--- | :--- | :--- |');
      for (final item in depReport!.issues) {
        final typeStr = item.issueType == DependencyIssueType.duplicate
            ? 'Duplicate Entry'
            : (item.scope == DependencyScope.dev
                ? 'Unused Dev Dep'
                : 'Unused Runtime Dep');
        buffer.writeln(
            '| `${item.packageName}` | `${item.scope.name}` | `$typeStr` | `${item.pubspecRelativePath}` |');
      }
      buffer.writeln();
      buffer.writeln('</details>');
      buffer.writeln();
    }

    // 6. Unused Media Assets & Fonts
    if (assetReport != null && assetReport!.unusedAssets.isNotEmpty) {
      buffer.writeln(
          '## 🖼️ Unused Media Assets & Fonts ($totalUnusedAssets - Reclaimable: ${formatByteSize(reclaimableAssetBytes)})');
      buffer.writeln();
      buffer.writeln(
          '<details><summary><b>Click to expand unreferenced media assets</b></summary>');
      buffer.writeln();
      buffer.writeln('| Asset Path | Category | File Size | Owning Package |');
      buffer.writeln('| :--- | :--- | :---: | :--- |');
      for (final item in assetReport!.unusedAssets) {
        buffer.writeln(
            '| `${item.path}` | `${item.category.name}` | `${item.sizeFormatted}` | `${item.ownerPackage.name}` |');
      }
      buffer.writeln();
      buffer.writeln('</details>');
      buffer.writeln();
    }

    // 7. Commented Files & Dead Code Blocks
    if (totalCommentedFiles > 0 || totalDeadBlocks > 0) {
      buffer.writeln('## 🚫 Commented-Out Files & Dead Blocks');
      buffer.writeln();
      if (totalCommentedFiles > 0) {
        buffer.writeln('### 100% Commented-Out Files ($totalCommentedFiles)');
        buffer.writeln();
        for (final f in report.fullyCommentedFiles) {
          final classes = f.commentedClasses.isNotEmpty
              ? ' (Classes: `${f.commentedClasses.join(', ')}`)'
              : '';
          buffer.writeln(
              '- 🔴 `${f.file}` - `${f.totalNonEmptyLines}` lines$classes');
        }
        buffer.writeln();
      }
      if (totalDeadBlocks > 0) {
        buffer.writeln(
            '### Active Files with Large Dead Blocks ($totalDeadBlocks)');
        buffer.writeln();
        for (final f in report.filesWithCommentBlocks) {
          buffer.writeln('- 🟡 `${f.file}`:');
          for (final b in f.blocks) {
            buffer.writeln(
                '  - Lines `L${b.startLine} - L${b.endLine}` (${b.totalLines} lines, ${b.codeLines} syntax lines)');
          }
        }
        buffer.writeln();
      }
    }

    // 8. Unused Imports & Diagnostics
    if (report.diagnostics.isNotEmpty) {
      buffer.writeln('## 🔍 Dart Analyzer Diagnostics ($totalDiagnostics)');
      buffer.writeln();
      buffer.writeln(
          '<details><summary><b>Click to expand analyzer diagnostic items</b></summary>');
      buffer.writeln();
      buffer.writeln('| Code | File | Line | Message |');
      buffer.writeln('| :--- | :--- | :---: | :--- |');
      for (final d in report.diagnostics) {
        buffer.writeln(
            '| `${d.code}` | `${d.file}` | `${d.line}` | ${d.message} |');
      }
      buffer.writeln();
      buffer.writeln('</details>');
      buffer.writeln();
    }

    // 9. Remediation & Quick Actions
    buffer.writeln('## 🧹 Quick Remediation Commands');
    buffer.writeln();
    buffer.writeln('```bash');
    buffer.writeln(
        '# Remediate all safe issues automatically with pre-modification snapshot:');
    buffer.writeln('detect_unused --clean-all');
    buffer.writeln();
    buffer.writeln('# Or open the interactive terminal dashboard:');
    buffer.writeln('detect_unused --interactive');
    buffer.writeln();
    buffer.writeln('# Rollback anytime instantly:');
    buffer.writeln('detect_unused --undo');
    buffer.writeln('```');
    buffer.writeln();

    return buffer.toString();
  }

  /// Writes the generated Markdown report directly to [filePath].
  File saveToFile(String filePath) {
    final file = File(filePath);
    file.writeAsStringSync(generate());
    return file;
  }
}
